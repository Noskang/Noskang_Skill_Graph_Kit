def text(lang, _msg, **kw):
    pair = MESSAGES.get(_msg)
    if pair is None:
        return str(_msg) + (' ' + repr(kw) if kw else '')
    template = pair[1] if lang == 'ko' else pair[0]
    return template.format(**kw)
